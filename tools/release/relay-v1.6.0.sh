#!/usr/bin/env bash
set -euo pipefail

# Daal relay artefact release — tag relay-v1.6.0.
#
# WHAT MOVED SINCE relay-v1.5.1 (commit 6814f34). daal-relay-mgmt: the
# add-ons' box half — the CDN door (singbox_cdn.go, its ufw handling in
# singbox_cdn_ufw.go), the `/cdn` route and the `cdn` capability, the
# standby address bind (address.go) — and "relays stop naming the app"
# (rotate-tls replaces a CN=daal-relay subject, tlscert.go; the mgmt
# certificate and the 401 body name nothing, main.go). daal-relay-health:
# publisher/deploy/health/ways.go, which it links. The artefact FILE
# NAMES still say 0.1.0; the bytes changed, so the tag moves (below).
#
# WHY A NEW TAG, NOT A RE-UPLOAD. A pin is a (URL, sha256, signature)
# triple. Uploading new bytes over an old URL (`gh release upload
# --clobber`) would
#
#   * break every build that still pins the old hash — CI stages the
#     published artefacts by exactly those URLs — and
#   * let any cache or mirror that still holds the old bytes answer a NEW
#     pin with them, which the box refuses ("artifact verification
#     failed") on a server somebody is already paying for.
#
# A release that changes bytes therefore gets a new tag, so the pinned
# URL changes with the hash. relay-v1.5.0, relay-v1.5.1 and their
# -mirror tags stay published, untouched, for the builds that pin them.
# NEVER re-upload under a tag that is already pinned anywhere: copy this
# script to the next tag instead.
#
# Without --upload this only builds, signs and stages under
# dist-release/$TAG/ — nothing leaves the machine. tools/release/README.md
# says what to do with the result.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TAG="relay-v1.6.0"
MIRROR_TAG="relay-v1.6.0-mirror"
REPO="${DAAL_RELEASE_REPO:-hastaan/daal}"
KEY="${DAAL_RELEASE_KEY:-$ROOT/release-keys/release.key}"
OUT="$ROOT/dist-release/$TAG"
VENDOR="$ROOT/tools/vendor"
GO_BIN="${GO_BIN:-go}"
SING_BOX_VERSION="1.13.12"
SING_BOX_TARBALL="sing-box-$SING_BOX_VERSION-linux-amd64.tar.gz"
SING_BOX_TARBALL_SHA256="1540533adb3df24f5ad5f14b5c7ca3dbc2401b10a1c1eb278fcadcada47ec6c4"
SING_BOX_URL="https://github.com/SagerNet/sing-box/releases/download/v$SING_BOX_VERSION/$SING_BOX_TARBALL"

usage() {
  cat <<USAGE
Usage: $0 [--upload]

Builds, signs, and stages relay artifacts under:
  $OUT

Set DAAL_RELEASE_KEY to override the private key path.
Set DAAL_RELEASE_REPO to override the GitHub repo.
USAGE
}

UPLOAD=0
for arg in "$@"; do
  case "$arg" in
    --upload) UPLOAD=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; usage >&2; exit 2 ;;
  esac
done

need() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "missing required command: $1" >&2
    exit 1
  }
}

need openssl
need sha256sum
need awk
need od
need tr
need tar

if [[ ! -f "$KEY" ]]; then
  echo "release key not found: $KEY" >&2
  echo "run tools/release/keygen.sh first" >&2
  exit 1
fi

mkdir -p "$OUT/work" "$VENDOR"
rm -f "$OUT"/*.sig "$OUT"/*.sig.hex "$OUT"/*.sha256 "$OUT"/artifacts.snippet.go

# Artefact builds MUST be reproducible: the hash produced here is pinned
# in publisher/deploy/cloudinit/artifacts.go, embedded into
# libdaal_deploy.so, and hash-verified by cloud-init on the box. Any byte
# that changes for a reason other than a source change turns a provision
# into "artifact verification failed".
#
# -buildvcs=false is therefore load-bearing, not tidiness. Go stamps
# vcs.revision and vcs.modified into the binary by default, which breaks
# reproducibility in two ways, both observed on 2026-08-18:
#
#   * vcs.modified flips with ANY uncommitted edit anywhere in the repo,
#     so the same source built from a clean tree and a dirty one gave
#     246e73eb and 7b251ec4. The second was uploaded against a pin
#     generated by the first.
#   * vcs.revision is the commit — and the pin for this binary lives in
#     that same commit. Committing the pin changes the revision, so a
#     stamped binary can NEVER correspond to the commit that pins it.
#     The dependency is circular by construction.
#
# Provenance comes from the Ed25519 signature and the release tag, which
# is what the box actually verifies. Do not re-enable the stamp.
build_go() {
  local pkg=$1
  local dst=$2
  (
    cd "$ROOT/$pkg"
    CGO_ENABLED=0 GOOS=linux GOARCH=amd64 "$GO_BIN" build -trimpath -buildvcs=false -ldflags="-s -w" -o "$OUT/$dst" .
  )
}

stage_sing_box() {
  local tarball="$VENDOR/$SING_BOX_TARBALL"
  if [[ ! -f "$tarball" ]]; then
    need curl
    curl -fsSL "$SING_BOX_URL" -o "$tarball"
  fi
  local got
  got="$(sha256sum "$tarball" | awk '{print $1}')"
  if [[ "$got" != "$SING_BOX_TARBALL_SHA256" ]]; then
    echo "sing-box tarball sha256 mismatch: got $got want $SING_BOX_TARBALL_SHA256" >&2
    exit 1
  fi
  rm -rf "$OUT/work/sing-box"
  mkdir -p "$OUT/work/sing-box"
  tar -xzf "$tarball" -C "$OUT/work/sing-box"
  cp "$OUT/work/sing-box/sing-box-$SING_BOX_VERSION-linux-amd64/sing-box" "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64"
  chmod 0755 "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64"
}

sign_artifact() {
  local file=$1
  local sig="$file.sig"
  openssl pkeyutl -sign -inkey "$KEY" -rawin -in "$file" -out "$sig"
  sha256sum "$file" | awk '{print $1}' > "$file.sha256"
  od -An -tx1 -v "$sig" | tr -d ' \n' > "$sig.hex"
  echo >> "$sig.hex"
}

url_for() {
  local tag=$1
  local name=$2
  printf 'https://github.com/%s/releases/download/%s/%s' "$REPO" "$tag" "$name"
}

emit_snippet() {
  local snippet="$OUT/artifacts.snippet.go"
  {
    echo "var V15Artifacts = ArtifactManifest{"
    echo '	Version: "v1.5.0",'
    echo "	Artefacts: []Artifact{"
    emit_artifact "sing-box-$SING_BOX_VERSION-linux-amd64" "sing-box"
    emit_artifact "daal-relay-health-0.1.0-linux-amd64" "daal-relay-health"
    echo "	},"
    echo "}"
    echo
    echo "var V2Artifacts = ArtifactManifest{"
    echo '	Version: "v2.0.0",'
    echo "	Artefacts: []Artifact{"
    emit_artifact "sing-box-$SING_BOX_VERSION-linux-amd64" "sing-box"
    emit_artifact "daal-relay-health-0.1.0-linux-amd64" "daal-relay-health"
    emit_artifact "daal-relay-mgmt-0.1.0-linux-amd64" "daal-relay-mgmt"
    echo "	},"
    echo "}"
  } > "$snippet"
  echo "$snippet"
}

emit_artifact() {
  local name=$1
  local install_as=$2
  local sha
  local sig
  sha="$(cat "$OUT/$name.sha256")"
  sig="$(cat "$OUT/$name.sig.hex")"
  cat <<GO
		{
			Name:      "$name",
			InstallAs: "$install_as",
			Sha256:    "$sha",
			SigHex:    "$sig",
			Mirrors: []string{
				"$(url_for "$TAG" "$name")",
				"$(url_for "$MIRROR_TAG" "$name")",
			},
		},
GO
}

upload_release() {
  need gh
  local tag=$1
  shift
  if gh release view "$tag" --repo "$REPO" >/dev/null 2>&1; then
    gh release upload "$tag" --repo "$REPO" --clobber "$@"
  else
    gh release create "$tag" --repo "$REPO" --title "$tag" --notes "Daal relay artifacts $tag" "$@"
  fi
}

# Fail the release rather than ship an unreproducible artefact. This
# catches a re-enabled stamp, a toolchain that stamps by default, or a
# future build_go that drops the flag — all of which look fine locally
# and only surface as a box that refuses to provision.
assert_no_vcs_stamp() {
  local file=$1
  if "$GO_BIN" version -m "$file" 2>/dev/null | grep -q 'vcs\.'; then
    echo "FATAL: $file carries a VCS stamp, so its hash depends on git state" >&2
    "$GO_BIN" version -m "$file" | grep 'vcs\.' >&2
    echo "The pin in publisher/deploy/cloudinit/artifacts.go could not stay valid." >&2
    echo "See the build_go comment above: -buildvcs=false is required." >&2
    exit 1
  fi
}

build_go "cmd/daal-relay-health" "daal-relay-health-0.1.0-linux-amd64"
build_go "cmd/daal-relay-mgmt" "daal-relay-mgmt-0.1.0-linux-amd64"
assert_no_vcs_stamp "$OUT/daal-relay-health-0.1.0-linux-amd64"
assert_no_vcs_stamp "$OUT/daal-relay-mgmt-0.1.0-linux-amd64"
stage_sing_box

for artifact in \
  "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64" \
  "$OUT/daal-relay-health-0.1.0-linux-amd64" \
  "$OUT/daal-relay-mgmt-0.1.0-linux-amd64"
do
  sign_artifact "$artifact"
done

emit_snippet

# The hashes above are a function of the source AND of the Go toolchain
# (relay-v1.5.0 was built with go1.26.0; the same source under go1.26.8
# gives different bytes). "Reproducible" therefore means: same tree, same
# `go version`. Written down beside the artefacts so a later rebuild that
# does not match can be told from a source change.
"$GO_BIN" version > "$OUT/toolchain.txt"

# The same commit that pastes the snippet has more to change, and the
# order matters (prove, upload, then push). It is written down once, in
# tools/release/README.md; say so here, every time.
cat >&2 <<NEXT

Staged under $OUT (nothing was uploaded$([[ "$UPLOAD" -eq 1 ]] && echo " yet")).
Toolchain: $(cat "$OUT/toolchain.txt")

The pin bump is ONE commit, and this snippet is only its first line.
Follow tools/release/README.md ("The pin bump") — it lists every constant
and file that moves with the pin, how to prove the candidate before
anything is uploaded, and when to run:  $0 --upload

NEXT

if [[ "$UPLOAD" -eq 1 ]]; then
  upload_release "$TAG" \
    "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64" \
    "$OUT/daal-relay-health-0.1.0-linux-amd64" \
    "$OUT/daal-relay-mgmt-0.1.0-linux-amd64" \
    "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64.sig" \
    "$OUT/daal-relay-health-0.1.0-linux-amd64.sig" \
    "$OUT/daal-relay-mgmt-0.1.0-linux-amd64.sig"
  upload_release "$MIRROR_TAG" \
    "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64" \
    "$OUT/daal-relay-health-0.1.0-linux-amd64" \
    "$OUT/daal-relay-mgmt-0.1.0-linux-amd64" \
    "$OUT/sing-box-$SING_BOX_VERSION-linux-amd64.sig" \
    "$OUT/daal-relay-health-0.1.0-linux-amd64.sig" \
    "$OUT/daal-relay-mgmt-0.1.0-linux-amd64.sig"
fi
