// -update-family-matrix regenerates testdata/client_outbounds.json.
// Regenerating is meant to be a deliberate act with a diff to read: the
// file is the contract two OTHER modules check themselves against, and a
// change to it is a change to the wire.
var updateFamilyMatrix = flag.Bool("update-family-matrix", false,
	"rewrite testdata/client_outbounds.json from the current renderer")

// familyMatrixPath is also hard-coded, relative to their own package
// directories, in:
//
//	core/engine/client_outbound_matrix_singbox_test.go   (does sing-box parse it?)
//	cmd/daal-relay-mgmt/box_client_agreement_test.go     (does the box agree with it?)
//
// If this file moves, both break loudly, which is the intent — a
// silently unread cross-check is worse than none.
const familyMatrixPath = "testdata/client_outbounds.json"

// matrixEntry is one family's rendered client half.
type matrixEntry struct {
	Port     int             `json:"port"`
	UDP      bool            `json:"udp"`
	Outbound json.RawMessage `json:"outbound"`
}

type familyMatrix struct {
	Doc      string                 `json:"doc"`
	Params   ClientConnParams       `json:"params"`
	Families map[string]matrixEntry `json:"families"`
}

const familyMatrixDoc = "Generated by publisher/deploy/relaypack TestClientOutboundMatrixIsCurrent " +
	"(go test ./deploy/relaypack -run TestClientOutboundMatrixIsCurrent -update-family-matrix). " +
	"Every entry is the REAL output of ClientOutboundForFamily for the fixed params below, at the " +
	"port relayports.For reports. It exists because the three halves of a transport family live in " +
	"three Go modules that cannot import each other: the publisher mints the client outbound, " +
	"cmd/daal-relay-mgmt serves the box inbound, and core/engine dials it. This file is the seam " +
	"they all check themselves against, so a family cannot mint a config the box does not serve or " +
	"sing-box will not parse. Do not hand-edit."

