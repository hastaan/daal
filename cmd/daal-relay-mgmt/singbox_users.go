func appendVLESSUser(doc map[string]any, c userCreds) error {
	in := findInboundByTag(doc, tagVLESS)
	if in == nil {
		return fmt.Errorf("sing-box config missing inbound with tag=%q", tagVLESS)
	}
	users, _ := in["users"].([]any)
	users = append(users, map[string]any{
		"uuid": c.VLESSUUID,
		"name": c.Name,
		"flow": "xtls-rprx-vision",
	})
	in["users"] = users
	// Append the Reality short_id.
	tlsBlock, _ := in["tls"].(map[string]any)
	if tlsBlock == nil {
		return errors.New("vless-in inbound has no tls block")
	}
	reality, _ := tlsBlock["reality"].(map[string]any)
	if reality == nil {
		return errors.New("vless-in inbound has no reality block")
	}
	sids, _ := reality["short_id"].([]any)
	sids = append(sids, c.RealityShortID)
	reality["short_id"] = sids
	return nil
}

func removeVLESSUser(doc map[string]any, name string) bool {
	in := findInboundByTag(doc, tagVLESS)
	if in == nil {
		return false
	}
	users, _ := in["users"].([]any)
	out := make([]any, 0, len(users))
	// Index correspondence is the whole mechanism: appendVLESSUser adds
	// the user and its REALITY short_id in the same call, in the same
	// order, so users[i] owns short_id[i]. Removing by index preserves
	// that invariant.
	//
	// Truncating the list to the new user count — what this used to do —
	// does not: revoking r1 (index 0) from [r1, r2] left short_id [A],
	// i.e. it revoked r2's credential and kept the revoked r1's. The
	// still-live recipient's vless-reality route, the primary 443/tcp
	// transport, then silently stopped working because someone *else*
	// was revoked.
	removed := make([]int, 0, 1)
	for i, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["name"].(string); n == name {
			removed = append(removed, i)
			continue
		}
		out = append(out, raw)
	}
	if len(removed) == 0 {
		return false
	}
	in["users"] = out

	tlsBlock, _ := in["tls"].(map[string]any)
	if tlsBlock != nil {
		reality, _ := tlsBlock["reality"].(map[string]any)
		if reality != nil {
			sids, _ := reality["short_id"].([]any)
			if len(sids) == len(users) {
				// Aligned: drop exactly the revoked user's entries.
				// Highest index first so earlier indices stay valid.
				for i := len(removed) - 1; i >= 0; i-- {
					j := removed[i]
					sids = append(sids[:j], sids[j+1:]...)
				}
				reality["short_id"] = sids
			} else if len(sids) > len(out) {
				// Not aligned (hand-edited config, or a box that
				// predates the paired append). There is no way to tell
				// which entry belongs to whom, so fall back to the old
				// truncation rather than leaving a stale credential
				// accepted — but never grow the list.
				reality["short_id"] = sids[:len(out)]
			}
		}
	}
	return true
}

func appendHy2User(doc map[string]any, c userCreds) error {
	in := findInboundByTag(doc, tagHy2)
	if in == nil {
		// Hy2 inbound is optional — UDP families may be disabled
		// per the toolbox profile.
		return nil
	}
	users, _ := in["users"].([]any)
	users = append(users, map[string]any{
		"name":     c.Name,
		"password": c.Hy2Password,
	})
	in["users"] = users
	return nil
}

func removeHy2User(doc map[string]any, name string) bool {
	in := findInboundByTag(doc, tagHy2)
	if in == nil {
		return false
	}
	users, _ := in["users"].([]any)
	out := make([]any, 0, len(users))
	for _, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["name"].(string); n == name {
			continue
		}
		out = append(out, raw)
	}
	if len(out) == len(users) {
		return false
	}
	in["users"] = out
	return true
}

func appendNaiveUser(doc map[string]any, c userCreds) error {
	in := findInboundByTag(doc, tagNaive)
	if in == nil {
		// Create the naive inbound on first use. Unlike vless/hy2 it
		// cannot ship empty: sing-box FATALs "missing users" when a
		// naive inbound has no users (protocol/naive/inbound.go), so it
		// only exists once it has one. The cert is the box's shared
		// data-plane leaf; the client pins it by SPKI SHA-256.
		in = map[string]any{
			"type":        "naive",
			"tag":         tagNaive,
			"listen":      "0.0.0.0",
			"listen_port": naiveListenPort,
			"users":       []any{},
			"tls": map[string]any{
				"enabled":          true,
				"certificate_path": tlsCertPath,
				"key_path":         tlsKeyPath,
			},
		}
		inbounds, _ := doc["inbounds"].([]any)
		doc["inbounds"] = append(inbounds, in)
	}
	users, _ := in["users"].([]any)
	users = append(users, map[string]any{
		"username": c.Name,
		"password": c.NaivePassword,
	})
	in["users"] = users
	return nil
}

func removeNaiveUser(doc map[string]any, name string) bool {
	in := findInboundByTag(doc, tagNaive)
	if in == nil {
		return false
	}
	users, _ := in["users"].([]any)
	out := make([]any, 0, len(users))
	for _, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["username"].(string); n == name {
			continue
		}
		out = append(out, raw)
	}
	if len(out) == len(users) {
		return false
	}
	if len(out) == 0 {
		// A naive inbound with an empty users[] FATALs on the next
		// sing-box start, so drop the whole inbound when its last user
		// leaves; appendNaiveUser re-creates it on the next add.
		inbounds, _ := doc["inbounds"].([]any)
		kept := make([]any, 0, len(inbounds))
		for _, raw := range inbounds {
			ib, _ := raw.(map[string]any)
			if t, _ := ib["tag"].(string); t == tagNaive {
				continue
			}
			kept = append(kept, raw)
		}
		doc["inbounds"] = kept
		return true
	}
	in["users"] = out
	return true
}

// appendTUICUser adds the recipient to the optional tuic-in inbound.
//
// Optional in the hy2 sense and never created here: a relay serves tuic
// only if it was provisioned with the inbound in its cloud-init
// sing-box config (toolbox profile enabled the family). A missing
// inbound is the normal case, not an error.
//
// TUIC rows carry BOTH a uuid and a password — sing-box's TUICUser has
// `uuid`, `password` and `name`, and the protocol authenticates on the
// pair. They are minted independently of the VLESS uuid so a leaked
// tuic pack does not also disclose the recipient's identity on the
// REALITY tier.
//
// Reports whether a row was appended.
func appendTUICUser(doc map[string]any, c userCreds) bool {
	in := findInboundByTag(doc, tagTUIC)
	if in == nil {
		return false
	}
	// Drift guard. The listen port is decided by relayports (publisher
	// module) and written by cloud-init; this binary only mirrors the
	// number. If the two ever disagree, the client outbound the
	// publisher renders would dial a port nothing is listening on, so
	// refuse the row rather than hand back creds for a dead route — the
	// publisher then fails closed exactly as it does for an old binary.
	if port, ok := numericPort(in["listen_port"]); ok && port != tuicListenPort {
		return false
	}
	users, _ := in["users"].([]any)
	for _, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["name"].(string); n == c.Name {
			return true // already present; idempotent
		}
	}
	in["users"] = append(users, map[string]any{
		"name":     c.Name,
		"uuid":     c.TUICUUID,
		"password": c.TUICPassword,
	})
	return true
}

// numericPort reads a listen_port out of a generic JSON decode, where a
// number arrives as float64 (and, from a hand-edited config, possibly as
// a string). Returns ok=false when the field is absent or unreadable, in
// which case callers must not treat it as a mismatch.
func numericPort(v any) (int, bool) {
	switch n := v.(type) {
	case float64:
		return int(n), true
	case int:
		return n, true
	case json.Number:
		i, err := n.Int64()
		if err != nil {
			return 0, false
		}
		return int(i), true
	}
	return 0, false
}

func removeTUICUser(doc map[string]any, name string) bool {
	in := findInboundByTag(doc, tagTUIC)
	if in == nil {
		return false
	}
	users, _ := in["users"].([]any)
	out := make([]any, 0, len(users))
	for _, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["name"].(string); n == name {
			continue
		}
		out = append(out, raw)
	}
	if len(out) == len(users) {
		return false
	}
	// Unlike naive, a tuic inbound with an empty users[] starts fine
	// (protocol/tuic/inbound.go has no "missing users" fatal), so the
	// inbound stays: dropping it would silently un-provision the family
	// for the relay when its last recipient is revoked.
	in["users"] = out
	return true
}

// tuicUserPresent reports whether the LIVE config really carries a tuic
// row for this recipient.
//
// This is the box's positive signal that the tuic tier exists here, and
// it is read back from the file rather than inferred from what this
// function believed it wrote. The publisher blanks the tuic creds when
// it is false and then fails closed on minting a tuic route, which is
// the only interlock that survives the release coupling: cloud-init and
// cmd/daal-relay-mgmt are pinned separately, so a fresh relay can boot
// with a tuic-in inbound in its config and an OLDER mgmt binary that
// has never heard of tuic. That binary answers /users/provision
// happily, adds no tuic row, and — without this — would hand back creds
// the publisher would mint into a route no one can dial.
func tuicUserPresent(path, name string) bool {
	doc, err := loadSingboxDoc(path)
	if err != nil {
		return false
	}
	in := findInboundByTag(doc, tagTUIC)
	if in == nil {
		return false
	}
	users, _ := in["users"].([]any)
	for _, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["name"].(string); n != name {
			continue
		}
		uuid, _ := u["uuid"].(string)
		pw, _ := u["password"].(string)
		return uuid != "" && pw != ""
	}
	return false
}

// appendWSUser adds the recipient to the single shared ws-in inbound
// (VLESS-over-WS on the WS-TLS port). Per-user ws inbounds would collide
// on the one shared port, so every recipient rides one inbound and is
// told apart by UUID (exactly like vless-in); they also share one ws
// path, fixed by the first recipient (see addUserToSingbox). Idempotent.
func appendWSUser(doc map[string]any, c userCreds) error {
	if in := findInboundByTag(doc, tagWS); in != nil {
		users, _ := in["users"].([]any)
		for _, raw := range users {
			u, _ := raw.(map[string]any)
			if n, _ := u["name"].(string); n == c.Name {
				return nil // already present
			}
		}
		in["users"] = append(users, map[string]any{
			"uuid": c.VLESSUUID,
			"name": c.Name,
		})
		return nil
	}
	// First ws recipient: create the shared inbound. Mirror the shared
	// TLS SNI from vless-in.
	sni := ""
	if vl := findInboundByTag(doc, tagVLESS); vl != nil {
		if t, _ := vl["tls"].(map[string]any); t != nil {
			if s, _ := t["server_name"].(string); s != "" {
				sni = s
			}
		}
	}
	inbound := map[string]any{
		"type":        "vless",
		"tag":         tagWS,
		"listen":      "0.0.0.0",
		"listen_port": wsListenPort,
		"users": []any{
			map[string]any{
				"uuid": c.VLESSUUID,
				"name": c.Name,
			},
		},
		"multiplex": muxInbound(),
		"transport": map[string]any{
			"type": "ws",
			"path": c.WSPath,
		},
		"tls": map[string]any{
			"enabled":          true,
			"server_name":      sni,
			"certificate_path": tlsCertPath,
			"key_path":         tlsKeyPath,
		},
	}
	inbounds, _ := doc["inbounds"].([]any)
	doc["inbounds"] = append(inbounds, inbound)
	return nil
}

// removeWSUser removes the recipient from the shared ws-in inbound,
// dropping the inbound entirely when the last user leaves (sing-box
// faults on a user-less inbound).
func removeWSUser(doc map[string]any, name string) bool {
	in := findInboundByTag(doc, tagWS)
	if in == nil {
		return false
	}
	users, _ := in["users"].([]any)
	out := make([]any, 0, len(users))
	removed := false
	for _, raw := range users {
		u, _ := raw.(map[string]any)
		if n, _ := u["name"].(string); n == name {
			removed = true
			continue
		}
		out = append(out, raw)
	}
	if !removed {
		return false
	}
	if len(out) == 0 {
		inbounds, _ := doc["inbounds"].([]any)
		kept := make([]any, 0, len(inbounds))
		for _, raw := range inbounds {
			i, _ := raw.(map[string]any)
			if t, _ := i["tag"].(string); t == tagWS {
				continue
			}
			kept = append(kept, raw)
		}
		doc["inbounds"] = kept
		return true
	}
	in["users"] = out
	return true
}

// wsInboundPath returns the shared ws-in inbound's ws path, or "" when
// no ws inbound exists yet.
func wsInboundPath(doc map[string]any) string {
	in := findInboundByTag(doc, tagWS)
	if in == nil {
		return ""
	}
	t, _ := in["transport"].(map[string]any)
	if t == nil {
		return ""
	}
	p, _ := t["path"].(string)
	return p
}

