package main

// address.go — the box half of L3 (the floating-IP swap).
//
// WHY THIS FILE EXISTS. A cloud floating IP is routed to the server at
// the PROVIDER's network layer. The provider API reports the attach as
// done in under a second, and it is done — the packets arrive. What
// does not happen is the guest OS answering them: Linux drops a packet
// whose destination is not an address configured on one of its
// interfaces. Measured on real hardware on 2026-08-17, an L3 swap did
// everything right at the API layer (reserved, attached, labelled,
// rewrote rec.PublicIP) and the box never answered on the new address
// while the old one kept serving. Nothing in this tree configured the
// address on the interface: cloud-init never writes it and the assign
// path is pure API.
//
// health.AddressServes already made that failure SAFE (the swap refuses
// and hands the address back). This file is what makes it WORK.
//
// NO SING-BOX CONFIG CHANGE IS NEEDED, and that is a load-bearing fact
// rather than a convenience. Every inbound this tree renders listens on
// 0.0.0.0 (profile_render.go:125,130; singbox_users.go:474,565,673,678),
// so sing-box accepts on any address the kernel holds for the host. The
// entire gap is "the OS does not hold the address". Adding it to the
// interface closes the gap completely — no inbound is touched, no
// config is rewritten, and therefore s.cfgMu is deliberately NOT taken
// on these paths (see addrMu).
//
// ---------------------------------------------------------------
// THREAT MODEL — this is root-level network configuration driven by a
// remote request, so it gets more than the signature it already sits
// behind.
//
// Who can call it: only the publisher. Both routes are wrapped in
// s.requireAuth, i.e. a per-request Ed25519 signature over
// nonce:ts:op verified against the per-deploy public key, inside a 5
// minute window, and the mgmt port is additionally shut by the cloud
// provider firewall except during an ephemeral allowlist window. That
// is the primary control and it is strong.
//
// Why we defend further anyway: the publisher's signing key lives on an
// operator's laptop, the operator is the person under pressure in this
// product's threat model, and a bug in the publisher is as dangerous
// here as a stolen key. The failure modes of an unbounded "configure
// any address on the host" primitive are severe and silent:
//
//   T1  Traffic hijack / route shadowing. Binding 127.0.0.1, a
//       link-local address, or an RFC1918 address that the box already
//       routes towards a gateway makes the host itself the destination
//       for that address. Local traffic aimed at an internal service
//       (metadata service on 169.254.169.254 is the sharpest example)
//       would be answered by this host instead of the real one.
//       MITIGATION: validateBindAddress rejects every non-public
//       unicast class by name — see the table there.
//
//   T2  Command injection. The live half shells out. A caller-supplied
//       string reaching a shell would be remote root code execution
//       behind one signature check.
//       MITIGATION, three layers: (a) a strict charset pre-filter
//       rejects anything outside hex digits, ':' and '.' before parsing
//       — no spaces, no ';', '$', '`', '|', newline, '%' zone-id or '/'
//       prefix can even reach the parser; (b) the address is parsed
//       with net.ParseIP and then RE-RENDERED from the parsed value, so
//       the bytes that leave this process are generated by Go's
//       formatter and never by the caller; (c) exec.Command is invoked
//       with an argv, never through a shell, so even a hostile argument
//       is one argv element and not a command. Any one of the three is
//       sufficient; all three are present because this is the endpoint
//       where being wrong is worst.
//
//   T3  Interface exhaustion. A buggy retry loop or a compromised
//       caller could add addresses until the interface, the netlink
//       tables or the persistence directory is unusable.
//       MITIGATION: maxBoundAddresses caps the set; the cap is checked
//       against the persisted record set, not against a counter, so a
//       restart cannot reset it.
//
//   T4  Self-eviction via unbind. `ip addr del <primary> dev eth0` on a
//       box with no SSH access is a permanent, unrecoverable outage —
//       strictly worse than anything bind can do. An unbind that
//       accepted any address would hand that button to whoever holds
//       the signing key, and to any publisher bug that passes the wrong
//       variable.
//       MITIGATION, TWO HALVES, and the second one was missing until
//       the Wave 3c repair. (a) unbind is RECORD-GATED: it will only
//       remove an address this service itself bound and still has a
//       persistence record for. An address that is not in the record
//       set is a no-op success (idempotence) and the interface is not
//       touched. (b) bind REFUSES TO ADOPT an address that is already
//       configured on the interface and is not already one of our
//       records — because adopting one is exactly how the primary
//       address would get INTO the record set, after which (a) permits
//       its removal. Two signed calls, bind(primary) then
//       unbind(primary), used to be enough to strand the relay for
//       good; see handleBindAddress. With both halves in place the
//       invariant "the primary address is never a record, so it can
//       never be removed through this API" is enforced rather than
//       merely hoped for.
//
//   T5  Stale persistence. An address released back to the provider
//       pool is re-issued to another customer. A persistence record we
//       forgot to remove would make this box claim a stranger's address
//       at the next reboot.
//       MITIGATION: bind undoes its own persistence when the live half
//       fails (see bind failure semantics below), and unbind removes
//       the live address FIRST and the record second, attempting both
//       even if the first fails, so the "still holding it" direction is
//       never the one we stop in.
//
// RESIDUAL, ACCEPTED: an authenticated caller can bind a public address
// that belongs to a neighbour on the same L2 segment and blackhole or
// ARP-hijack it. The box cannot detect this — only the provider knows
// which addresses are actually routed here, and the box has no way to
// ask. We reduce the blast radius by adding every address as a HOST
// prefix (/32, /128) so a bind can never claim a whole subnet or
// disturb the existing on-link route, and we do not reject
// same-subnet addresses because several providers legitimately hand out
// additional addresses from the server's own subnet and rejecting them
// would break the feature for those providers.

