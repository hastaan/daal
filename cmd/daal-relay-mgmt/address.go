// capBindAddress is the capability token the box advertises on
// GET /health when it can ACTUALLY configure addresses on this host.
//
// It is a wire contract with publisher/deploy/mgmt, exactly like
// capRotateCredentialsScoped: the publisher fails closed on its
// absence, so the literal is the contract and not the constant name.
//
// TWO THINGS ABOUT THIS TOKEN ARE DELIBERATE.
//
// First, it is advertised CONDITIONALLY, unlike the two rotation
// tokens. Those describe what the binary does; this one describes
// something the binary cannot do alone. Configuring an address needs
// CAP_NET_ADMIN, and cloud-init decides whether this service has it.
// Older relays (and any box whose unit was hand-edited) run
// daal-relay-mgmt with `CapabilityBoundingSet=CAP_NET_BIND_SERVICE` and
// `NoNewPrivileges=true` — root, but without the capability, and unable
// to acquire it. So a box can be running this exact binary and still be
// unable to bind. Advertising the verb from the binary version alone
// would be the publisher's interlock reporting a capability that does
// not exist, and the failure would land halfway through a swap. The
// probe (probeAddressBinding) asks whether this process can ACTUALLY
// configure addresses, and only then does the token appear.
//
// ONE TOKEN COVERS BOTH VERBS, so the probe must be true of both. It
// was not: a box that could only delegate to the boot unit advertised
// the token, and the boot unit only ADDS. Every unbind on such a box
// was a guaranteed 500 — which turns a failed swap's rollback and the
// whole `floating-ip release` path into dead ends, and hands addresses
// back to the provider pool while the box still holds them. The probe
// now requires the capability this process can use for BOTH directions;
// see probeAddressBinding.
//
// Second, and following from the first: the publisher must treat this
// token as the ONLY signal for address binding. It must NOT add a
// mgmt_api_version fallback for it the way BoxCapabilities.Has does for
// the two rotation verbs, because the version says what the binary is
// and this capability is a property of how the binary was launched.
// As shipped it does exactly that — BoxCapabilities.Has has no version
// branch for CapBindAddress — and this comment is the reason it must
// stay that way.
const capBindAddress = "bind-address"

// maxBoundAddresses bounds T3.
//
// THIS NUMBER IS SHARED WITH THE PUBLISHER (mgmt.MaxBoundAddresses = 4)
// and the two must stay equal. The box is the enforcement point,
// because it is the only party that can see the interface; the
// publisher re-checks the count this box reports in bound_addresses and
// refuses a box that reports more, so a mismatch shows up as a loud
// refusal of a legitimate bind rather than as a slowly filling
// interface. Four covers a v4/v6 pair on each side of a swap and leaves
// no room for a runaway.
//
// Enforced against the PERSISTED set, not an in-memory counter, so a
// restart cannot reset it.
const maxBoundAddresses = 4

// bootUnitName is the oneshot systemd unit that re-applies the
// persisted record set after a reboot. See ensureBootUnit for why
// persistence is a unit and not a netplan file.
const bootUnitName = "daal-bound-addresses.service"

// addrCharset is the T2 pre-filter. Hex digits, ':' and '.' are
// everything any textual IP literal needs; nothing else is accepted, so
// shell metacharacters, whitespace, newlines, '%' zone identifiers and
// '/' prefix lengths are rejected before net.ParseIP is even reached.
// Length is bounded so an enormous body cannot be walked.
var addrCharset = regexp.MustCompile(`^[0-9a-fA-F:.]{2,45}$`)

// ifaceNameRe validates the interface name before it becomes an argv
// element. The name is derived from the kernel, never from the caller,
// so this is belt-and-braces against a future refactor that lets one in.
var ifaceNameRe = regexp.MustCompile(`^[A-Za-z0-9._-]{1,15}$`)

// --- validation -------------------------------------------------------

// rejectedRange is one row of the T1 validation table. `why` names the
// range in the words an operator can look up, because "invalid address"
// on a remote box with no SSH is not an actionable error.
type rejectedRange struct {
	cidr string
	why  string
	net  *net.IPNet
}

// rejectedRanges is the T1 table: every address class that must never be
// configured on this host in response to a remote request.
//
// The list is explicit rather than delegated to ip.IsGlobalUnicast()
// because that helper returns TRUE for RFC1918 and CGNAT space — it
// answers "is this a unicast address with global scope semantics", not
// "is this an address the public internet could route here". Both are
// applied: the table first (so the error names the range) and
// IsGlobalUnicast afterwards as a catch-all for anything the table
// misses.
//
// THE DOCUMENTATION RANGES ARE DELIBERATELY ABSENT (192.0.2.0/24,
// 198.51.100.0/24, 203.0.113.0/24, 2001:db8::/32), and the omission is
// a reconciliation with publisher/deploy/mgmt.BindableAddress, which
// allows them. The two validators MUST agree, and this is the direction
// they were made to agree in, for two reasons:
//
//   - Nothing this table exists to prevent is reachable through them.
//     They shadow no internal route, carry no metadata service, hijack
//     no traffic on the host, and no provider will ever issue one — so
//     the worst a bound documentation address can do is be an address
//     the relay answers on and nobody can reach.
//   - The stricter end has to be the FIRST end or its strictness buys
//     nothing. The publisher validates before it reserves or attaches
//     anything; this box validates last. A row present here and absent
//     there does not prevent a bad bind, it only moves the refusal to
//     after an address has been reserved, attached and a firewall
//     window opened — which is the failure shape this whole wave exists
//     to remove.
//
// They also have one property no real address has: a test may DIAL them
// and be certain nobody answers. Refusing them would push every
// reachability test in this tree onto some third party's real address.
//
// 192.88.99.0/24 stays rejected, and is the row that shows the rule is
// harm-based rather than "not routable": 6to4 relay anycast has real
// routing meaning, so binding it can attract or shadow traffic. The
// publisher was tightened to match it rather than the reverse.
var rejectedRanges = func() []rejectedRange {
	rows := []rejectedRange{
		// IPv4.
		{cidr: "0.0.0.0/8", why: "unspecified / \"this network\" 0.0.0.0/8"},
		{cidr: "10.0.0.0/8", why: "RFC1918 private 10.0.0.0/8"},
		{cidr: "100.64.0.0/10", why: "RFC6598 carrier-grade NAT 100.64.0.0/10"},
		{cidr: "127.0.0.0/8", why: "loopback 127.0.0.0/8"},
		{cidr: "169.254.0.0/16", why: "link-local 169.254.0.0/16 (includes the cloud metadata service at 169.254.169.254)"},
		{cidr: "172.16.0.0/12", why: "RFC1918 private 172.16.0.0/12"},
		{cidr: "192.0.0.0/24", why: "IETF protocol assignments 192.0.0.0/24"},
		{cidr: "192.88.99.0/24", why: "deprecated 6to4 relay anycast 192.88.99.0/24"},
		{cidr: "192.168.0.0/16", why: "RFC1918 private 192.168.0.0/16"},
		{cidr: "198.18.0.0/15", why: "benchmarking 198.18.0.0/15"},
		{cidr: "224.0.0.0/4", why: "multicast 224.0.0.0/4"},
		{cidr: "240.0.0.0/4", why: "reserved 240.0.0.0/4 (includes the 255.255.255.255 broadcast address)"},
		// IPv6.
		{cidr: "::/128", why: "unspecified ::"},
		{cidr: "::1/128", why: "loopback ::1"},
		// ::ffff:0:0/96 (IPv4-mapped) is deliberately NOT a row here,
		// and the omission is load-bearing rather than an oversight.
		// net.ParseCIDR renders that prefix as a value whose To4() is
		// non-nil, so IPNet.Contains reduces its /96 mask to the LAST
		// FOUR BYTES — which are all zero — and the row silently
		// becomes 0.0.0.0/0, rejecting every IPv4 address on earth.
		// The disguise is caught by the textual check in
		// validateBindAddress instead, which is the only place it is
		// actually visible: after parsing, ::ffff:127.0.0.1 and
		// 127.0.0.1 are the same 16 bytes.
		{cidr: "64:ff9b::/96", why: "NAT64 well-known prefix 64:ff9b::/96"},
		{cidr: "100::/64", why: "discard-only 100::/64"},
		{cidr: "2001::/32", why: "Teredo 2001::/32"},
		{cidr: "2002::/16", why: "deprecated 6to4 2002::/16"},
		{cidr: "fc00::/7", why: "unique-local fc00::/7"},
		{cidr: "fe80::/10", why: "link-local fe80::/10"},
		{cidr: "ff00::/8", why: "multicast ff00::/8"},
	}
	for i := range rows {
		_, n, err := net.ParseCIDR(rows[i].cidr)
		if err != nil {
			// Unreachable: the table is a compile-time constant in
			// everything but name. Panicking here beats shipping a
			// validator with a silently missing row.
			panic("address.go: bad rejectedRanges entry " + rows[i].cidr + ": " + err.Error())
		}
		rows[i].net = n
	}
	return rows
}()

// validateBindAddress is the whole of T1 and layers (a) and (b) of T2.
//
// It returns the CANONICAL address, re-rendered by Go's formatter from
// the parsed value. Callers must use the returned net.IP and must never
// carry the caller's string forward — that is the property that makes
// every downstream use (argv element, filename, JSON echo) injection
// proof by construction rather than by review.
func validateBindAddress(raw string) (net.IP, error) {
	s := strings.TrimSpace(raw)
	if s == "" {
		return nil, errors.New(`"ip" is required`)
	}
	if !addrCharset.MatchString(s) {
		// Deliberately does NOT echo the input. This error can reach a
		// log or an operator's terminal, and reflecting arbitrary bytes
		// from a rejected request is how a validator becomes an
		// injection vector for the thing reading its output.
		return nil, errors.New("malformed address: only hexadecimal digits, ':' and '.' are accepted " +
			"(no prefix length, no zone id, no whitespace)")
	}
	ip := net.ParseIP(s)
	if ip == nil {
		return nil, fmt.Errorf("not a valid IP address: %q", s)
	}
	// An IPv4-mapped literal (::ffff:127.0.0.1) parses to a 16-byte
	// value whose To4() is non-nil, so it would otherwise sail through
	// the IPv4 half of the table wearing IPv6 clothes and then be
	// rendered back as plain 127.0.0.1. Caught here by the TEXTUAL
	// form, which is the ONLY place the disguise is visible: after
	// parsing, ::ffff:127.0.0.1 and 127.0.0.1 are the same bytes. See
	// the note in rejectedRanges for why this cannot be a table row.
	if strings.Contains(s, ":") && ip.To4() != nil {
		return nil, errors.New("rejected: IPv4-mapped IPv6 ::ffff:0:0/96 — send the plain IPv4 form instead")
	}
	for _, r := range rejectedRanges {
		// Compare in the family the row was written in: a 4-byte v4
		// value and a 16-byte v6 range must not match each other.
		probe := ip
		if r.net.IP.To4() != nil {
			if probe = ip.To4(); probe == nil {
				continue
			}
		} else if ip.To4() != nil {
			continue
		}
		if r.net.Contains(probe) {
			return nil, fmt.Errorf("rejected %s: not a public unicast address (%s)", canonicalIP(ip), r.why)
		}
	}
	// Catch-all for anything the table does not enumerate.
	if !ip.IsGlobalUnicast() {
		return nil, fmt.Errorf("rejected %s: not a global unicast address", canonicalIP(ip))
	}
	if ip.To4() != nil {
		return ip.To4(), nil
	}
	return ip, nil
}

// canonicalIP renders a parsed address. Every string this file emits —
// argv elements, persistence filenames, JSON responses, error text —
// comes from here and therefore from Go's formatter.
func canonicalIP(ip net.IP) string { return ip.String() }

// prefixLen returns the HOST prefix for the family. Always /32 or /128,
// never the interface's subnet prefix: a host route claims exactly one
// address and cannot rewrite the on-link route the box needs to reach
// its gateway. See the residual-risk note in the threat model.
func prefixLen(ip net.IP) int {
	if ip.To4() != nil {
		return 32
	}
	return 128
}

// --- persistence ------------------------------------------------------

// PERSISTENCE: WHY A SYSTEMD ONESHOT AND NOT NETPLAN.
//
// The box is a cloud-init Ubuntu 24.04 image (providers/hetzner:
// "ubuntu-24.04"). Its network is described by netplan
// (/etc/netplan/50-cloud-init.yaml) rendered to systemd-networkd, so
// netplan is the image's native mechanism and the provider's own
// documentation for floating IPs says to add a netplan file. It was
// still rejected, for three reasons in increasing order of weight:
//
//  1. Netplan merges files by key, and a list-valued key in a
//     higher-numbered file REPLACES the same key from a lower-numbered
//     one rather than appending to it. Writing `addresses:` for eth0
//     works today only because the cloud-init file configures the
//     primary address by DHCP and so has no `addresses:` list to
//     replace. That is a property of one provider's image, not of the
//     format, and it is invisible until the day it changes.
//
//  2. Applying it is not free. `netplan apply` reconfigures the live
//     interface, and the one moment we run it is mid-rotation, while
//     the box MUST keep answering on the old address — the entire
//     safety property of the fail-closed swap. `ip addr add` is
//     strictly additive and cannot remove anything.
//
//  3. Blast radius, which is decisive. A malformed file in
//     /etc/netplan fails the whole configuration at boot, and this box
//     has no SSH access by design. The failure mode of a bad netplan
//     write is a relay that never comes back and can only be
//     destroyed and reprovisioned. The failure mode of a bad unit file
//     is one oneshot service that fails while the network comes up
//     normally — recoverable, visible, and no worse than not having
//     bound the address at all, which is the state health.AddressServes
//     already fails closed on.
//
// So: the record set is a directory of one file per address, and a
// systemd oneshot re-applies it after network-online.target. The unit
// runs THIS binary with -reapply-addresses, so the boot path and the
// live path are the same validated code — a record that would be
// rejected today is rejected at boot too, and there is no shell script
// to drift.
//
// The rejected alternative worth naming: a drop-in in
// /etc/systemd/network. A .network file there matching eth0 would
// SHADOW netplan's generated unit in /run/systemd/network instead of
// adding to it, taking DHCP with it. Same unrecoverable outcome as (3).
//
// KNOWN LIMIT, stated rather than papered over: an address added with
// `ip addr add` is "foreign" to systemd-networkd. A full
// `networkctl reconfigure` or a `netplan apply` run by something else
// on the box can flush it before the next reboot. Nothing on this box
// does either today, and the address is restored at the next boot;
// re-asserting it live is one `systemctl restart daal-bound-addresses`
// away, and the reapply path is idempotent precisely so that is safe.

// boundRecordFile maps an address to its persistence filename.
//
// Built from the CANONICAL rendering, not the caller's string, so no
// caller-supplied byte reaches a path. ':' becomes '_' purely to keep
// the names easy to read and type; the file's CONTENT is the
// authoritative value and readers re-parse and re-validate it, so the
// name is never trusted. The two families cannot collide: an IPv4 name
// contains '.' and never '_', an IPv6 name the reverse.
func boundRecordFile(dir string, ip net.IP) string {
	name := strings.ReplaceAll(canonicalIP(ip), ":", "_")
	return filepath.Join(dir, name+".addr")
}

// listBoundRecords returns the persisted address set, canonical and
// sorted.
//
// Every record is re-parsed and re-validated on the way out. A record
// that no longer passes validateBindAddress — a hand-edited file, a
// record written by a future version with looser rules, a corrupted
// write — is SKIPPED and named in the returned warnings rather than
// applied. The boot path uses this function too, so a record that could
// not be created through the API can never be applied by the reboot
// either.
func listBoundRecords(dir string) ([]net.IP, []string, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil, nil
	}
	if err != nil {
		return nil, nil, err
	}
	var out []net.IP
	var warns []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".addr") {
			continue
		}
		body, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			warns = append(warns, fmt.Sprintf("record %s unreadable: %v", e.Name(), err))
			continue
		}
		ip, err := validateBindAddress(strings.TrimSpace(string(body)))
		if err != nil {
			warns = append(warns, fmt.Sprintf("record %s ignored: %v", e.Name(), err))
			continue
		}
		out = append(out, ip)
	}
	sort.Slice(out, func(i, j int) bool { return canonicalIP(out[i]) < canonicalIP(out[j]) })
	return out, warns, nil
}

// writeBoundRecord persists one address, temp-file-then-rename so a
// crash mid-write cannot leave a half-written record that the boot path
// would then have to interpret.
//
// 0o600 / 0o700: the record set is operational configuration for a
// privileged action. Nothing unprivileged on the box needs to read it,
// and a world-writable record directory would turn a local unprivileged
// bug into "choose which address this host claims at next boot".
func writeBoundRecord(dir string, ip net.IP) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	path := boundRecordFile(dir, ip)
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(canonicalIP(ip)+"\n"), 0o600); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

// removeBoundRecord deletes the record for ip. Absent is success:
// rotations are retried, and "already gone" is the outcome the caller
// asked for.
//
// It removes by CONTENT, walking the directory and comparing parsed
// values, not by recomputing the filename. Two spellings of the same
// address must not be able to leave a second file behind, and a record
// written by an older or newer naming scheme still has to be removable.
func removeBoundRecord(dir string, ip net.IP) (removed bool, err error) {
	entries, rerr := os.ReadDir(dir)
	if errors.Is(rerr, os.ErrNotExist) {
		return false, nil
	}
	if rerr != nil {
		return false, rerr
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".addr") {
			continue
		}
		p := filepath.Join(dir, e.Name())
		body, readErr := os.ReadFile(p)
		if readErr != nil {
			continue
		}
		got := net.ParseIP(strings.TrimSpace(string(body)))
		if got == nil || !got.Equal(ip) {
			continue
		}
		if delErr := os.Remove(p); delErr != nil && !errors.Is(delErr, os.ErrNotExist) {
			err = delErr
			continue
		}
		removed = true
	}
	return removed, err
}

