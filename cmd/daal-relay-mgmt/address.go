// detectPrimaryInterface picks the NIC the box's public traffic arrives
// on.
//
// Preference order: an up, non-loopback, non-point-to-point interface
// that already holds a PUBLIC address (that is the WAN NIC by
// definition); failing that, one holding any global unicast address (a
// box behind provider NAT). Virtual and container interfaces are
// excluded by name because a bridge with a private address would
// otherwise win the fallback and the address would be configured
// somewhere the internet cannot reach.
//
// Ties break on the lowest interface index, which is eth0 on every
// image this tree provisions (cloud-init's own probe hardcodes eth0 —
// v2.yaml.tmpl:284 — so agreeing with it is the conservative choice).
func detectPrimaryInterface() (string, error) {
	ifaces, err := net.Interfaces()
	if err != nil {
		return "", fmt.Errorf("enumerate interfaces: %w", err)
	}
	sort.Slice(ifaces, func(i, j int) bool { return ifaces[i].Index < ifaces[j].Index })
	fallback := ""
	for _, ifc := range ifaces {
		if ifc.Flags&net.FlagUp == 0 || ifc.Flags&net.FlagLoopback != 0 {
			continue
		}
		if ifc.Flags&net.FlagPointToPoint != 0 {
			continue // tun/wg/ppp: not where a provider routes a floating IP
		}
		if isVirtualIfaceName(ifc.Name) || !ifaceNameRe.MatchString(ifc.Name) {
			continue
		}
		addrs, err := ifc.Addrs()
		if err != nil {
			continue
		}
		for _, a := range addrs {
			n, ok := a.(*net.IPNet)
			if !ok || n.IP == nil || !n.IP.IsGlobalUnicast() {
				continue
			}
			if _, verr := validateBindAddress(n.IP.String()); verr == nil {
				return ifc.Name, nil // holds a public address: this is the WAN NIC
			}
			if fallback == "" {
				fallback = ifc.Name
			}
		}
	}
	if fallback != "" {
		return fallback, nil
	}
	return "", errors.New("no candidate interface: no up, non-loopback interface holds a global unicast address")
}

// isVirtualIfaceName excludes the usual container/virtual plumbing so it
// cannot win the private-address fallback in detectPrimaryInterface.
func isVirtualIfaceName(name string) bool {
	for _, p := range []string{"docker", "veth", "br-", "virbr", "tun", "tap", "wg", "cni", "flannel", "kube", "lo"} {
		if strings.HasPrefix(name, p) {
			return true
		}
	}
	return false
}

// defaultAddrList reads the addresses currently configured on an
// interface. Pure Go, read-only, needs no capability — which is what
// lets this process VERIFY the outcome of an apply it may have had to
// delegate. "Did it work" is answered by looking, never by trusting the
// exit status of the thing we asked to do it.
func defaultAddrList(iface string) ([]net.IP, error) {
	ifc, err := net.InterfaceByName(iface)
	if err != nil {
		return nil, err
	}
	addrs, err := ifc.Addrs()
	if err != nil {
		return nil, err
	}
	out := make([]net.IP, 0, len(addrs))
	for _, a := range addrs {
		switch v := a.(type) {
		case *net.IPNet:
			out = append(out, v.IP)
		case *net.IPAddr:
			out = append(out, v.IP)
		}
	}
	return out, nil
}

// defaultAddrAdd runs `ip addr add <ip>/<hostprefix> dev <iface>`.
//
// exec.Command takes an argv and does NOT go through a shell (T2 layer
// c). Both variable elements are generated here: the address from
// canonicalIP over a parsed net.IP, the interface from the kernel via
// ifaceNameRe. No caller byte is present in this command line.
//
// "File exists" is success. Idempotence has to hold at this layer too,
// not only at the layer above, because the presence check and the add
// are not atomic and a retried rotation is the normal case.
func defaultAddrAdd(iface string, ip net.IP) error {
	if !ifaceNameRe.MatchString(iface) {
		return fmt.Errorf("refusing to use interface name %q", iface)
	}
	cidr := canonicalIP(ip) + "/" + strconv.Itoa(prefixLen(ip))
	out, err := exec.Command("ip", "addr", "add", cidr, "dev", iface).CombinedOutput()
	if err == nil {
		return nil
	}
	if strings.Contains(strings.ToLower(string(out)), "file exists") {
		return nil
	}
	return fmt.Errorf("ip addr add %s dev %s: %w (%s)", cidr, iface, err, strings.TrimSpace(string(out)))
}

// defaultAddrDel runs `ip addr del`. Same argv discipline. "Cannot
// assign requested address" / "not exist" is success for the same
// idempotence reason.
func defaultAddrDel(iface string, ip net.IP) error {
	if !ifaceNameRe.MatchString(iface) {
		return fmt.Errorf("refusing to use interface name %q", iface)
	}
	cidr := canonicalIP(ip) + "/" + strconv.Itoa(prefixLen(ip))
	out, err := exec.Command("ip", "addr", "del", cidr, "dev", iface).CombinedOutput()
	if err == nil {
		return nil
	}
	low := strings.ToLower(string(out))
	if strings.Contains(low, "cannot assign requested address") || strings.Contains(low, "not exist") {
		return nil
	}
	return fmt.Errorf("ip addr del %s dev %s: %w (%s)", cidr, iface, err, strings.TrimSpace(string(out)))
}

// defaultSystemdStart re-runs the boot unit to apply the record set
// under CAP_NET_ADMIN. It is the delegation path: talking to PID 1
// needs root, not CAP_NET_ADMIN, and the unit systemd then launches
// carries the capability ambiently. The argv is wholly constant.
//
// IT MUST BE `restart`, NOT `start`. The unit is Type=oneshot with
// RemainAfterExit=yes, so after it has run at boot it sits in
// "active (exited)" — and `systemctl start` on an already-active unit
// is a NO-OP that exits ZERO without re-running ExecStart. Using
// `start` would therefore succeed silently on every box that had
// rebooted since its first bind, apply nothing, and hand back a
// zero exit for work that never happened. `restart` always re-runs
// ExecStart. (The verification read in ensureLive would still catch it
// and fail the bind, so this is the difference between "L3 works" and
// "L3 refuses on every rebooted relay" rather than a silent-success
// hole — but it is the whole feature either way.)
//
// Both verbs are synchronous for a oneshot: systemctl waits for
// ExecStart to finish and exits non-zero if the unit failed, so this is
// a real answer and not a fire-and-forget.
func defaultSystemdStart(unit string) error {
	out, err := exec.Command("systemctl", "restart", unit).CombinedOutput()
	if err != nil {
		return fmt.Errorf("systemctl restart %s: %w (%s)", unit, err, strings.TrimSpace(string(out)))
	}
	return nil
}

func defaultSystemdReload() error {
	out, err := exec.Command("systemctl", "daemon-reload").CombinedOutput()
	if err != nil {
		return fmt.Errorf("systemctl daemon-reload: %w (%s)", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// holdsCapNetAdmin reads the effective capability set from
// /proc/self/status.
//
// This is not a guess about how the process was started, it is what the
// kernel will enforce on the next netlink write. CAP_NET_ADMIN is bit
// 12. On a relay provisioned by the CURRENT cloud-init this returns
// true (daal-relay-mgmt.service carries
// AmbientCapabilities=CAP_NET_ADMIN); on one provisioned before that
// change it returns false, and probeAddressBinding then refuses the
// whole capability rather than advertise a bind it could not undo.
func holdsCapNetAdmin() bool {
	const capNetAdmin = 12
	body, err := os.ReadFile("/proc/self/status")
	if err != nil {
		return false
	}
	for _, line := range strings.Split(string(body), "\n") {
		if !strings.HasPrefix(line, "CapEff:") {
			continue
		}
		v, err := strconv.ParseUint(strings.TrimSpace(strings.TrimPrefix(line, "CapEff:")), 16, 64)
		if err != nil {
			return false
		}
		return v&(1<<capNetAdmin) != 0
	}
	return false
}

func haveBinary(name string) bool {
	_, err := exec.LookPath(name)
	return err == nil
}

// probeAddressBinding answers "can this box actually configure an
// address", which is a different question from "does this binary
// implement /bind-address".
//
// It is why capBindAddress is conditional. If the answer is no, the
// honest thing is to advertise nothing and let the publisher refuse
// with the Step-7 message, because a bind that cannot work must fail
// BEFORE the provider attach, not halfway through the swap.
//
// IT REQUIRES CAP_NET_ADMIN IN THIS PROCESS, and the reason is the
// half of the contract that has no delegation. This probe used to
// accept "systemctl exists" as sufficient, on the grounds that the
// boot unit runs under AmbientCapabilities=CAP_NET_ADMIN and can apply
// the record set for us. That is true of BINDING and false of
// UNBINDING: applyBoundRecords only ADDS (it must — at boot the
// interface holds the primary address, which is not a record, and a
// reconcile that removed non-records would delete it). So a box
// advertising the token off the systemd route promised two verbs and
// could only perform one, and the one it could not perform is the one
// on the failure paths: the rollback of a swap whose probe failed, and
// every `floating-ip release`. Both then hand an address back to the
// provider's pool while this box still has it configured — the exact
// T5 harm the ordering elsewhere in this file exists to prevent.
//
// The cloud-init this tree ships therefore grants the capability to
// daal-relay-mgmt.service (AmbientCapabilities=CAP_NET_ADMIN, matching
// sing-box.service on the same box). That is not a widening of what
// this process can already reach: it runs as root, writes
// /etc/systemd/system and asks PID 1 to start a unit it authored with
// AmbientCapabilities=CAP_NET_ADMIN — see ensureBootUnit — so the
// bounding set was never a boundary for it. Holding the capability
// directly only makes the two verbs symmetric and the failure honest.
//
// A relay provisioned before that cloud-init change reports FALSE here
// and the publisher refuses L3 on it, cleanly and before anything is
// reserved. That is the correct answer for such a box: it can bind and
// not unbind, so the swap it could perform is one it could never undo.
//
// systemctl is still required. Persistence is a systemd unit, and
// ensureBootUnit's daemon-reload failure is fatal to a bind (a record
// with no unit to re-apply it dies silently at the next reboot), so a
// box with no systemctl cannot honour the contract either.
//
// The returned note is diagnostic text for an operator who cannot SSH
// into the box to find out why the verb is missing — "too old binary",
// "no capability" and "no iproute2" have completely different remedies
// and an unexplained absence sends them to the wrong one.
func probeAddressBinding() (bool, string) {
	if !haveBinary("ip") {
		return false, "address binding unavailable: the `ip` utility (iproute2) is not installed on this box"
	}
	if !haveBinary("systemctl") {
		return false, "address binding unavailable: there is no systemctl, so an address could be configured now but not " +
			"persisted across a reboot (persistence is the " + bootUnitName + " oneshot)"
	}
	if !holdsCapNetAdmin() {
		return false, "address binding unavailable: this service holds no CAP_NET_ADMIN. It could still ADD an address by " +
			"delegating to " + bootUnitName + ", but it could never REMOVE one (the boot unit only adds), and a relay that can " +
			"bind without being able to unbind hands addresses back to the provider pool while it still holds them. " +
			"Reprovision this relay: the current cloud-init grants AmbientCapabilities=CAP_NET_ADMIN to daal-relay-mgmt.service"
	}
	return true, "address binding available: applied in-process (CAP_NET_ADMIN held)"
}

// --- reconciliation ---------------------------------------------------

// applyBoundRecords makes the interface hold every persisted record.
//
// ONE reconcile-from-records function serves the live bind, the retry
// after a delegated apply, and the boot path. That is deliberate: the
// alternative — "apply this one address" for the live path and "apply
// them all" at boot — is two code paths that must agree about
// validation and rendering forever, which is the shape of the bug this
// whole wave is fixing.
//
// It only ADDS. Removing an address the records do not mention is not
// this function's job: at boot the interface holds the primary address,
// which is not and must never be a record (T4).
func (s *server) applyBoundRecords(iface string) (applied []net.IP, warns []string, err error) {
	records, warns, err := listBoundRecords(s.boundAddrDir)
	if err != nil {
		return nil, warns, fmt.Errorf("read bound-address records: %w", err)
	}
	if len(records) == 0 {
		return nil, warns, nil
	}
	live, err := s.addrList(iface)
	if err != nil {
		return nil, warns, fmt.Errorf("list addresses on %s: %w", iface, err)
	}
	for _, want := range records {
		if containsIP(live, want) {
			applied = append(applied, want)
			continue
		}
		if aerr := s.addrAdd(iface, want); aerr != nil {
			err = errors.Join(err, aerr)
			continue
		}
		applied = append(applied, want)
	}
	return applied, warns, err
}

func containsIP(set []net.IP, want net.IP) bool {
	for _, got := range set {
		if got.Equal(want) {
			return true
		}
	}
	return false
}

// ensureLive brings ip up on the interface and VERIFIES it by reading
// the interface back, returning the method that worked.
//
// Two routes, tried in order:
//
//	direct   — `ip addr add` in this process. Needs CAP_NET_ADMIN,
//	           which probeAddressBinding now REQUIRES before the verb
//	           is advertised at all (only this route can also remove an
//	           address), so on any box that reaches this handler it is
//	           the route that works.
//	systemd  — `systemctl restart daal-bound-addresses.service`, which
//	           reconciles the record set (already written by the
//	           caller) under a unit PID 1 grants CAP_NET_ADMIN to. Kept
//	           as a fallback for the case where the direct add fails
//	           for a reason other than the capability, and because it
//	           is the same reconcile the boot path runs.
//
// The direct attempt is made first and its failure is not fatal.
// Whatever route ran, success is decided by LOOKING at the interface
// afterwards — a delegated apply hands back an exit status about a
// unit, not about an address, and reporting "bound" on the strength of
// that is how L3 came to claim success against a box that never
// answered. That rule applies to the FAILING branches too: a
// reconcile that could not apply some OTHER record exits non-zero
// while having applied ours, so the non-zero exit is re-checked
// against the interface rather than believed.
func (s *server) ensureLive(iface string, ip net.IP) (method string, warns []string, err error) {
	live, lerr := s.addrList(iface)
	if lerr != nil {
		return "", nil, fmt.Errorf("list addresses on %s: %w", iface, lerr)
	}
	if containsIP(live, ip) {
		return "already", nil, nil
	}

	var attempts []string
	if derr := s.addrAdd(iface, ip); derr != nil {
		attempts = append(attempts, "direct: "+derr.Error())
	} else if s.addrPresent(iface, ip) {
		return "direct", warns, nil
	} else {
		attempts = append(attempts, "direct: `ip addr add` reported success but the address is not on "+iface)
	}

	if s.systemdStart != nil {
		if serr := s.systemdStart(bootUnitName); serr != nil {
			// A non-zero exit is a statement about the UNIT, not about
			// this address. reapplyBoundAddresses fails the unit if ANY
			// record could not be applied, so a reconcile that put our
			// address on the interface and stumbled over an unrelated
			// stale record exits non-zero. Believing that would fail the
			// bind and then undo the persistence for an address that is
			// live — leaving it configured with no record, which the
			// record gate (T4) makes permanently unremovable through
			// this API. So look before concluding, exactly as the
			// success branch does.
			if s.addrPresent(iface, ip) {
				warns = append(warns, "applied via the "+bootUnitName+" delegation path, but that unit reported a failure "+
					"("+serr.Error()+"): "+canonicalIP(ip)+" IS on "+iface+", so this bind stands — some other persisted "+
					"address could not be applied and needs looking at")
				return "systemd", warns, nil
			}
			attempts = append(attempts, "systemd: "+serr.Error())
		} else if s.addrPresent(iface, ip) {
			// Said through Warnings because there is no wire field for
			// it and an invented one would be silently dropped by the
			// publisher's struct. An operator needs to know the apply
			// went through a unit rather than through this process.
			warns = append(warns, "applied via the "+bootUnitName+" delegation path: this service holds no CAP_NET_ADMIN")
			return "systemd", warns, nil
		} else {
			attempts = append(attempts, "systemd: "+bootUnitName+" ran but the address is not on "+iface)
		}
	}
	return "", warns, fmt.Errorf("could not configure %s on %s: %s",
		canonicalIP(ip), iface, strings.Join(attempts, "; "))
}

// addrPresent re-reads the interface. Verification is always a fresh
// read; a cached list from before the mutation would answer a question
// nobody asked.
func (s *server) addrPresent(iface string, ip net.IP) bool {
	live, err := s.addrList(iface)
	if err != nil {
		return false
	}
	return containsIP(live, ip)
}

