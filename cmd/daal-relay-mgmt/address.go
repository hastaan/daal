// bootUnitBody renders the oneshot unit.
//
// ExecStart names THIS executable (os.Executable, resolved at write
// time) with a fixed flag and no caller-derived content anywhere in the
// file, so the unit cannot become an injection surface even though it
// is written in response to a remote request.
//
// AmbientCapabilities=CAP_NET_ADMIN is the point of the unit beyond
// persistence: PID 1 grants it, so the boot-time apply holds the
// capability the long-running mgmt service is denied. See
// probeAddressBinding.
func bootUnitBody(exePath string) string {
	return "[Unit]\n" +
		"Description=Daal: re-apply operator-bound addresses (floating IPs) to the primary interface\n" +
		"After=network-online.target\n" +
		"Wants=network-online.target\n" +
		"\n" +
		"[Service]\n" +
		"Type=oneshot\n" +
		"RemainAfterExit=yes\n" +
		"ExecStart=" + exePath + " -reapply-addresses\n" +
		"AmbientCapabilities=CAP_NET_ADMIN\n" +
		"CapabilityBoundingSet=CAP_NET_ADMIN\n" +
		"\n" +
		"[Install]\n" +
		"WantedBy=multi-user.target\n"
}

// ensureBootUnit installs (or refreshes) the unit and its enablement
// symlink, idempotently.
//
// The symlink is created directly rather than through
// `systemctl enable`, because that is exactly what enable does for a
// WantedBy=multi-user.target unit and doing it ourselves removes a
// dependency on systemctl succeeding for the half of the operation that
// must not be best-effort. `systemctl daemon-reload` is then called
// best-effort: without it the unit is still picked up at the next boot,
// which is the only moment it runs.
//
// This is called BEFORE the record is persisted, and its failure is
// fatal to the bind. A record with no unit to re-apply it is precisely
// the "silently dies at the next reboot" outcome the persistence
// requirement exists to prevent, so a box that cannot host the unit
// must refuse to bind rather than bind and lie.
func (s *server) ensureBootUnit() error {
	if s.bootUnitPath == "" {
		return errors.New("boot unit path not configured")
	}
	exe, err := os.Executable()
	if err != nil || strings.TrimSpace(exe) == "" {
		// Fall back to the path cloud-init installs to. Better a unit
		// naming the canonical location than no persistence at all.
		exe = "/usr/local/bin/daal-relay-mgmt"
	}
	body := bootUnitBody(exe)
	if cur, rerr := os.ReadFile(s.bootUnitPath); rerr == nil && string(cur) == body {
		// Already correct; still make sure the enablement link is there.
		return s.ensureBootUnitEnabled()
	}
	if err := os.MkdirAll(filepath.Dir(s.bootUnitPath), 0o755); err != nil {
		return fmt.Errorf("boot unit dir: %w", err)
	}
	tmp := s.bootUnitPath + ".tmp"
	if err := os.WriteFile(tmp, []byte(body), 0o644); err != nil {
		return fmt.Errorf("boot unit write: %w", err)
	}
	if err := os.Rename(tmp, s.bootUnitPath); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("boot unit install: %w", err)
	}
	if err := s.ensureBootUnitEnabled(); err != nil {
		return err
	}
	// The reload is NOT best-effort, and the reason is easy to get
	// wrong. systemd does not learn about a unit file that appeared
	// after its last reload, so without this:
	//
	//   - `systemctl restart daal-bound-addresses` fails with "unit not
	//     found" — and on the box as shipped that IS the apply path,
	//     because this service holds no CAP_NET_ADMIN; and
	//   - the enablement symlink we just wrote is not acted on, so the
	//     unit may not run at the next boot either, which is the
	//     persistence guarantee itself.
	//
	// A box where daemon-reload fails is a box where neither half can
	// be promised, so it refuses the bind rather than reporting
	// persisted=true over a unit systemd has never seen. Only called on
	// the path where the file actually changed, so a steady-state
	// re-bind does not pay for it.
	if s.systemdReload != nil {
		if err := s.systemdReload(); err != nil {
			return fmt.Errorf("systemd did not accept the persistence unit (it would neither run at boot nor be startable now): %w", err)
		}
	}
	return nil
}

func (s *server) ensureBootUnitEnabled() error {
	if s.bootUnitWantsPath == "" {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(s.bootUnitWantsPath), 0o755); err != nil {
		return fmt.Errorf("boot unit enable dir: %w", err)
	}
	if cur, err := os.Readlink(s.bootUnitWantsPath); err == nil && cur == s.bootUnitPath {
		return nil
	}
	_ = os.Remove(s.bootUnitWantsPath)
	if err := os.Symlink(s.bootUnitPath, s.bootUnitWantsPath); err != nil && !errors.Is(err, os.ErrExist) {
		return fmt.Errorf("boot unit enable: %w", err)
	}
	return nil
}

