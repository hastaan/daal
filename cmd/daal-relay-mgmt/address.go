// bindAddressResp is the answer to POST /bind-address.
//
// WIRE CONTRACT WITH publisher/deploy/mgmt.BindAddressResp. Every field
// name and type here is matched there, and that is not cosmetic: the
// publisher's struct SILENTLY DROPS unknown JSON keys, so a field this
// box invents dies in the middle of the hop with no error anywhere.
// That has already made one feature in this tree inert. Anything the
// box wants to say that has no field goes into Warnings, which the
// publisher renders verbatim — that is the only channel that cannot
// silently swallow a value.
//
// Persisted is separate from the status code on purpose. It is the
// field that separates "answers on this address now" from "answers on
// this address", and a caller that can only see 200 cannot tell a relay
// that survives a reboot from one that dies at 3am on a date nobody
// will connect to anything.
//
// BoundAddresses is the OPERATOR-BOUND record set — the addresses this
// API added and can remove — not every address on the interface. The
// primary address is deliberately absent: it is not something this API
// manages, it can never be unbound through it (see handleUnbindAddress,
// T4), and counting it against maxBoundAddresses would spend a quarter
// of the budget on an address no swap ever touches.
type bindAddressResp struct {
	IP             string   `json:"ip"`
	Interface      string   `json:"interface,omitempty"`
	AlreadyBound   bool     `json:"already_bound"`
	Persisted      bool     `json:"persisted"`
	PersistPath    string   `json:"persist_path,omitempty"`
	BoundAddresses []string `json:"bound_addresses,omitempty"`
	AppliedAtUnix  int64    `json:"applied_at_unix,omitempty"`
	Warnings       []string `json:"warnings,omitempty"`
}

// unbindAddressResp is the answer to POST /unbind-address, matched field
// for field with publisher/deploy/mgmt.UnbindAddressResp.
//
// The publisher reads these three together and each has a precise
// meaning it acts on:
//
//	WasBound=false, Removed=false            the idempotent no-op.
//	WasBound=true,  Removed=false            a FAILURE the box chose to
//	                                         report as 200; the caller
//	                                         treats it as an error.
//	Removed=true, PersistenceRemoved=false   live now, back at the next
//	                                         reboot, on an address this
//	                                         relay no longer owns.
//
// So Removed means "the address is no longer configured on the
// interface", which is answered by RE-READING the interface after the
// attempt — not by whether `ip addr del` exited zero. A record that was
// persisted but never live reports Removed=true because the statement
// is true, and reporting false would send the publisher down the
// "still configured" error path for a box that is in exactly the state
// the caller asked for.
//
// StillConfigured is the fourth reading and it exists because the third
// one had no field. When the address is NOT ours, this handler answers
// 200 with WasBound=false, Removed=false — the publisher's "no-op,
// nothing to do" reading — and puts "…but it IS on the interface and I
// did not remove it" in Warnings. Warnings are prose: mgmt.UnbindAddress
// could not act on it, every publisher call site discarded the struct,
// and `floating-ip release` went on to hand the address back to the
// provider's pool while this box was still answering on it. That is the
// T5 harm with the alarm wired to nothing. A machine-readable field is
// the fix; the publisher turns it into a hard error.
type unbindAddressResp struct {
	IP                 string   `json:"ip"`
	Removed            bool     `json:"removed"`
	WasBound           bool     `json:"was_bound"`
	PersistenceRemoved bool     `json:"persistence_removed"`
	StillConfigured    bool     `json:"still_configured"`
	BoundAddresses     []string `json:"bound_addresses,omitempty"`
	AppliedAtUnix      int64    `json:"applied_at_unix,omitempty"`
	Warnings           []string `json:"warnings,omitempty"`
}

// renderIPs renders a record set for the wire, canonical and sorted.
func renderIPs(ips []net.IP) []string {
	if len(ips) == 0 {
		return nil
	}
	out := make([]string, 0, len(ips))
	for _, ip := range ips {
		out = append(out, canonicalIP(ip))
	}
	sort.Strings(out)
	return out
}

// handleBindAddress configures a provider-routed address on the guest
// OS so the box actually answers on it.
//
// ORDER, AND WHY IT IS PERSIST-FIRST. The operation has two halves and
// a crash can land between them, so the question is not "can both
// fail" but "which residue is survivable".
//
//	persisted, not live   — the box does not answer on the address. The
//	                        publisher's health.AddressServes probe fails
//	                        and the swap refuses, hands the address back
//	                        and keeps the record on the working one.
//	                        LOUD, immediate, already handled.
//	live, not persisted   — the box answers. Every probe passes, the
//	                        swap commits, the operator is told it
//	                        worked. Then a reboot months later drops the
//	                        address and the relay dies for reasons
//	                        nobody can connect to anything. SILENT and
//	                        undateable.
//
// So the persistent record is written first and the live address
// second, because the only residue a crash can leave is the loud one.
//
// When the live half fails outright, the handler UNDOES the persistence
// before returning the error, so a refusal leaves nothing behind for
// the next reboot to claim (T5) — and the response says so. The boot
// unit is installed before either half, because a record with no unit
// to re-apply it is the silent-death case with extra steps.
func (s *server) handleBindAddress(w http.ResponseWriter, r *http.Request) {
	if r.Method != "POST" {
		http.Error(w, "method", http.StatusMethodNotAllowed)
		return
	}
	s.bindAddrCnt.Add(1)

	var req bindAddressReq
	if err := json.NewDecoder(io.LimitReader(r.Body, 4096)).Decode(&req); err != nil && !errors.Is(err, io.EOF) {
		http.Error(w, "decode: "+err.Error(), http.StatusBadRequest)
		return
	}
	ip, err := validateBindAddress(req.IP)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	// Refuse rather than half-apply if this box cannot actually do it.
	// The same answer /health advertises, so a publisher that honoured
	// the capability never reaches this; a publisher that did not gets
	// a 501 naming the reason instead of a partially bound box.
	if ok, note := s.addrCapability(); !ok {
		http.Error(w, note, http.StatusNotImplemented)
		return
	}

	// A dedicated mutex, NOT s.cfgMu. These handlers do not read or
	// write the sing-box config at all — every inbound already listens
	// on 0.0.0.0, so holding a new address needs no config change — and
	// taking the config lock here would serialise address work behind
	// multi-second rotations for no reason. What does need serialising
	// is the record set: the count check, the write and the apply must
	// not interleave with a concurrent unbind of the same address.
	s.addrMu.Lock()
	defer s.addrMu.Unlock()

	iface, err := s.primaryIface()
	if err != nil {
		http.Error(w, "interface: "+err.Error(), http.StatusInternalServerError)
		return
	}
	records, warns, err := listBoundRecords(s.boundAddrDir)
	if err != nil {
		http.Error(w, "read bound-address records: "+err.Error(), http.StatusInternalServerError)
		return
	}
	alreadyRecorded := containsIP(records, ip)

	// T4, THE HALF THAT WAS MISSING. Refuse to ADOPT an address that is
	// already on the interface and is not already one of our records.
	//
	// The unbind gate is "is it in the record set", and the claim that
	// makes that gate safe is "the primary address is never in the
	// record set". Nothing enforced the claim. Binding an address the
	// box already holds looked like a harmless no-op — validation
	// passes for any public unicast address, ensureLive answers
	// "already" and touches nothing — but it WROTE A RECORD, and a
	// record is precisely what makes an address removable. Two signed
	// calls, bind(primary) then unbind(primary), would then run
	// `ip addr del <primary> dev eth0` on a relay with no SSH: an
	// unrecoverable outage reachable by a leaked publisher key or by a
	// publisher bug that passes the wrong address variable, which are
	// exactly the residual threats this file says it defends against.
	//
	// Refusing costs nothing on the intended path: an L3 binds an
	// address the provider has just routed here and the guest OS does
	// NOT yet hold — that is the entire hardware finding. An address
	// already configured needs no bind, and if it is genuinely ours the
	// record exists and alreadyRecorded short-circuits this check.
	//
	// The read is fresh rather than reusing anything, because the
	// question is about the interface right now.
	if !alreadyRecorded {
		live, lerr := s.addrList(iface)
		if lerr != nil {
			http.Error(w, "list addresses on "+iface+": "+lerr.Error(), http.StatusInternalServerError)
			return
		}
		if containsIP(live, ip) {
			http.Error(w, fmt.Sprintf(
				"refusing to bind %s: it is already configured on %s and this service did not put it there. "+
					"Adopting it would add it to the record set, and anything in the record set can be removed through "+
					"/unbind-address — including this box's own primary address, whose removal is an unrecoverable outage "+
					"on a relay with no SSH. Nothing needs doing: the box already answers on this address",
				canonicalIP(ip), iface), http.StatusConflict)
			return
		}
	}

	// T3: the cap is checked against the persisted set, so a restart
	// cannot reset it. Re-binding an address already recorded is not a
	// new address and never trips the cap.
	if !alreadyRecorded && len(records) >= maxBoundAddresses {
		http.Error(w, fmt.Sprintf(
			"refusing to bind %s: this relay already holds %d operator-bound addresses, the maximum is %d — unbind one first",
			canonicalIP(ip), len(records), maxBoundAddresses), http.StatusConflict)
		return
	}

	// Persistence, half one of two: the unit that re-applies records
	// after a reboot. Fatal on failure — see the handler comment.
	if err := s.ensureBootUnit(); err != nil {
		http.Error(w, "persistence unavailable, refusing to bind an address that would be lost at the next reboot: "+err.Error(),
			http.StatusInternalServerError)
		return
	}
	// Persistence, half two: the record itself. Before the live half.
	if !alreadyRecorded {
		if err := writeBoundRecord(s.boundAddrDir, ip); err != nil {
			http.Error(w, "persist bound address: "+err.Error(), http.StatusInternalServerError)
			return
		}
	}

	// The live half.
	method, liveWarns, err := s.ensureLive(iface, ip)
	warns = append(warns, liveWarns...)
	if err != nil {
		// Undo our own persistence so a refusal leaves nothing for the
		// next reboot to claim (T5). Only what we just wrote: if the
		// record predates this call, some earlier successful bind owns
		// it and removing it here would silently unbind a working
		// address on behalf of a failed request.
		undone := "record left in place (it predates this request)"
		if !alreadyRecorded {
			if _, rerr := removeBoundRecord(s.boundAddrDir, ip); rerr != nil {
				undone = "WARNING: could not remove the persistence record just written (" + rerr.Error() +
					") — this box may claim " + canonicalIP(ip) + " at its next reboot"
			} else {
				undone = "persistence record removed; nothing was left behind"
			}
		}
		http.Error(w, err.Error()+" — "+undone, http.StatusInternalServerError)
		return
	}

	after, moreWarns, _ := listBoundRecords(s.boundAddrDir)
	warns = append(warns, moreWarns...)
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(bindAddressResp{
		IP:        canonicalIP(ip),
		Interface: iface,
		// "already" is the verdict from re-reading the interface: the
		// record was there AND the address was live. A record that had
		// gone stale on the interface and was just re-applied is NOT
		// already-bound, because something removed it and the operator
		// should see that this call had work to do.
		AlreadyBound:   alreadyRecorded && method == "already",
		Persisted:      true,
		PersistPath:    boundRecordFile(s.boundAddrDir, ip),
		BoundAddresses: renderIPs(after),
		AppliedAtUnix:  s.now().Unix(),
		Warnings:       dedupeWarnings(warns),
	})
}

// handleUnbindAddress removes an address this service bound.
//
// RECORD-GATED (T4). The interface is touched only for an address that
// is in the persistence record set. `ip addr del <primary> dev eth0` on
// a box with no SSH is an unrecoverable outage, and an unbind that
// accepted any address would put that one netlink call behind a single
// signature — reachable by a stolen key, and equally by a publisher bug
// that passes the wrong variable. The primary address is never a
// record, so it is not reachable from here at all — and bind refuses to
// adopt a live address precisely so that stays true. An unrecorded
// address is a quiet success, never an error: rotations retry, and "it
// is not bound by us" is the state the caller wanted. If it is
// nevertheless ON the interface, `still_configured` says so and the
// publisher stops before releasing it.
//
// ORDER, AND WHY IT IS THE REVERSE OF BIND. Here the dangerous residue
// is the box CONTINUING to hold an address the provider has taken back
// and re-issued to someone else, so the urgent half is the live one and
// it goes first. Neither half short-circuits the other: both are always
// attempted and both are reported, because stopping halfway through a
// removal leaves exactly the state the removal existed to prevent.
// Validation here is intentionally parse-only, without the public-range
// table: the record set is a far stronger gate than any range check,
// and refusing to clean up a record that somehow fell outside the
// ranges would strand it.
func (s *server) handleUnbindAddress(w http.ResponseWriter, r *http.Request) {
	if r.Method != "POST" {
		http.Error(w, "method", http.StatusMethodNotAllowed)
		return
	}
	s.unbindAddrCnt.Add(1)

	var req bindAddressReq
	if err := json.NewDecoder(io.LimitReader(r.Body, 4096)).Decode(&req); err != nil && !errors.Is(err, io.EOF) {
		http.Error(w, "decode: "+err.Error(), http.StatusBadRequest)
		return
	}
	raw := strings.TrimSpace(req.IP)
	if raw == "" {
		http.Error(w, `"ip" is required`, http.StatusBadRequest)
		return
	}
	// The T2 charset filter still applies — this value also becomes an
	// argv element — but the T1 range table does not; see the handler
	// comment.
	if !addrCharset.MatchString(raw) {
		http.Error(w, "malformed address: only hexadecimal digits, ':' and '.' are accepted", http.StatusBadRequest)
		return
	}
	ip := net.ParseIP(raw)
	if ip == nil {
		http.Error(w, fmt.Sprintf("not a valid IP address: %q", raw), http.StatusBadRequest)
		return
	}
	if v4 := ip.To4(); v4 != nil {
		ip = v4
	}

	s.addrMu.Lock()
	defer s.addrMu.Unlock()

	iface, ierr := s.primaryIface()
	records, warns, rerr := listBoundRecords(s.boundAddrDir)
	if rerr != nil {
		http.Error(w, "read bound-address records: "+rerr.Error(), http.StatusInternalServerError)
		return
	}
	recorded := containsIP(records, ip)

	resp := unbindAddressResp{
		IP:            canonicalIP(ip),
		WasBound:      recorded,
		AppliedAtUnix: s.now().Unix(),
	}
	if !recorded {
		// Not ours. Idempotent success (WasBound=false, Removed=false
		// is the publisher's no-op reading), and we say what we saw
		// rather than pretending the address is gone: if it IS live on
		// the interface, something other than this service put it there
		// — the primary address being the obvious candidate — and a
		// human needs to know this call did not remove it.
		resp.PersistenceRemoved = true // there was no record to remove
		if ierr == nil && s.addrPresent(iface, ip) {
			// The machine-readable half of the same sentence. See
			// unbindAddressResp: the prose below cannot stop a caller
			// from releasing the address, and this field can.
			resp.StillConfigured = true
			warns = append(warns, canonicalIP(ip)+" is configured on "+iface+" but was not bound by this service, "+
				"so it was NOT removed: this API only removes addresses it added, because removing the box's "+
				"primary address would be an unrecoverable outage on a relay with no SSH")
		}
		after, moreWarns, _ := listBoundRecords(s.boundAddrDir)
		warns = append(warns, moreWarns...)
		resp.BoundAddresses = renderIPs(after)
		resp.Warnings = dedupeWarnings(warns)
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(resp)
		return
	}

	// Live half FIRST, then the record; both attempted regardless.
	var failures []string
	if ierr != nil {
		failures = append(failures, "interface: "+ierr.Error())
	} else if s.addrPresent(iface, ip) {
		if err := s.addrDel(iface, ip); err != nil {
			// There is NO delegated fallback for a removal: the boot
			// unit only ADDS (it must — the primary address is not a
			// record and a reconcile that removed non-records would
			// delete it). That asymmetry is why probeAddressBinding
			// refuses to advertise this verb at all unless THIS process
			// holds CAP_NET_ADMIN, so reaching here with a permission
			// error means the box's unit was changed under us.
			// Report honestly and still remove the record, so at least
			// the next reboot does not re-assert an address the
			// provider may have re-issued to someone else.
			failures = append(failures, err.Error())
		}
	}
	removedRec, derr := removeBoundRecord(s.boundAddrDir, ip)
	resp.PersistenceRemoved = removedRec || derr == nil
	if derr != nil {
		failures = append(failures, "remove persistence record: "+derr.Error())
	}
	// Removed is decided by LOOKING, after both halves have run. A
	// record that was persisted but never live reports true, which is
	// the truthful statement "the address is not configured here".
	if ierr == nil {
		resp.Removed = !s.addrPresent(iface, ip)
		// Same statement, same source of truth, both branches: "is it
		// on the interface now". This one already fails with a 500, but
		// a field that meant different things on different paths would
		// be worse than no field.
		resp.StillConfigured = !resp.Removed
		if !resp.Removed && len(failures) == 0 {
			failures = append(failures, "`ip addr del` reported success but "+canonicalIP(ip)+" is still on "+iface)
		}
	}
	after, moreWarns, _ := listBoundRecords(s.boundAddrDir)
	warns = append(warns, moreWarns...)
	resp.BoundAddresses = renderIPs(after)
	resp.Warnings = dedupeWarnings(warns)

	if len(failures) > 0 {
		http.Error(w, fmt.Sprintf("unbind %s incomplete (live removed=%t, persistence removed=%t): %s",
			canonicalIP(ip), resp.Removed, resp.PersistenceRemoved, strings.Join(failures, "; ")),
			http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(resp)
}

func dedupeWarnings(in []string) []string {
	if len(in) == 0 {
		return nil
	}
	seen := map[string]bool{}
	var out []string
	for _, w := range in {
		if w == "" || seen[w] {
			continue
		}
		seen[w] = true
		out = append(out, w)
	}
	return out
}

// --- the boot path ----------------------------------------------------

// reapplyBoundAddresses is what the oneshot unit runs. It reconciles the
// record set onto the primary interface and reports per-record outcomes
// to the journal, which is the only place a human can read them on a
// box with no SSH.
//
// It shares applyBoundRecords with the live path, so validation and
// rendering cannot drift between "bound now" and "bound after a
// reboot".
func reapplyBoundAddresses(dir string, logf func(string, ...any)) error {
	s := &server{
		boundAddrDir: dir,
		addrList:     defaultAddrList,
		addrAdd:      defaultAddrAdd,
		now:          time.Now,
	}
	records, warns, err := listBoundRecords(dir)
	for _, w := range warns {
		logf("bound-addresses: %s", w)
	}
	if err != nil {
		return fmt.Errorf("read bound-address records: %w", err)
	}
	if len(records) == 0 {
		logf("bound-addresses: no records in %s; nothing to apply", dir)
		return nil
	}
	iface, err := detectPrimaryInterface()
	if err != nil {
		return err
	}
	applied, _, applyErr := s.applyBoundRecords(iface)
	for _, ip := range applied {
		logf("bound-addresses: %s is configured on %s", canonicalIP(ip), iface)
	}
	if applyErr != nil {
		// Non-zero exit: systemd marks the unit failed, which is the
		// only signal a human gets that this relay is not holding an
		// address it is supposed to hold.
		return applyErr
	}
	if len(applied) != len(records) {
		return fmt.Errorf("applied %d of %d recorded addresses on %s", len(applied), len(records), iface)
	}
	return nil
}
